// Redesign (V18-V24): builds src/app/v2.css from the design handoff, and keeps the old (V11) stylesheet off new pages.
//
//   node scripts/build-v2-css.mjs            -> writes src/app/v2.css
//   node scripts/build-v2-css.mjs --scope-old -> also rewrites src/app/globals.css once so its rules only apply on
//                                                 pages WITHOUT a .v2 root (run once; it is idempotent)
//
// v2.css = the union of every design page's <style> (base kit + page components + the RESP responsive layer), in the
// order first seen. Every selector is scoped to the new page root `.v2` (the design's `.root`), html/body rules apply
// only when a .v2 page is on screen, and keyframes are renamed v2-* so they never clash with the old ones.
// During the redesign a page is either fully old or fully new; when the last old page is gone, globals.css goes too.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = path.dirname(fileURLToPath(import.meta.url));
const FRONT = path.resolve(here, '..');
const SRC = path.resolve(FRONT, '../design-handoff/design/source');
const OUT = path.join(FRONT, 'src/app/v2.css');

const ROOTSEL = '.v2';
const scopeNew = (sel) => {
  sel = sel.trim();
  if (sel === ':root') return ':root';
  if (/^(html|body)\b/.test(sel)) return sel.replace(/^(html|body)/, '$1:has(.v2)');
  if (sel.startsWith('.root')) return ROOTSEL + sel.slice(5);          // .root.ar -> .v2.ar
  return `${ROOTSEL} ${sel}`;
};

function scopeRules(root, scope, renameKf) {
  const kf = new Map();
  root.walkAtRules('keyframes', (a) => {
    if (!renameKf) return;
    const n = renameKf(a.params);
    kf.set(a.params, n);
    a.params = n;
  });
  root.walkRules((r) => {
    if (r.parent?.type === 'atrule' && /keyframes/.test(r.parent.name)) return;
    r.selectors = r.selectors.map(scope);
  });
  if (kf.size) {
    root.walkDecls(/^animation(-name)?$/, (d) => {
      d.value = d.value.replace(/[A-Za-z_][\w-]*/g, (w) => kf.get(w) ?? w);
    });
  }
}

// ---- new stylesheet -----------------------------------------------------------------------------------------
const files = fs.readdirSync(SRC).filter((f) => f.endsWith('.dc.html')).sort();
const seen = new Set();
const out = postcss.root();
const key = (n) => (n.parent?.type === 'atrule' ? '@' + n.parent.name + ' ' + n.parent.params + '|' : '') + n.toString().replace(/\s+/g, ' ');
for (const f of ['../styles/app-base.css', ...files]) {
  const txt = fs.readFileSync(path.join(SRC, f), 'utf8');
  const css = f.endsWith('.css') ? txt : (txt.match(/<style>([\s\S]*?)<\/style>/) || [, ''])[1];
  const root = postcss.parse(css);
  root.each((node) => {
    if (node.type === 'comment') return;
    if (node.type === 'atrule' && node.name === 'media') {
      // merge media blocks rule by rule
      let target = out.nodes.find((n) => n.type === 'atrule' && n.name === 'media' && n.params === node.params);
      if (!target) {
        target = postcss.atRule({ name: 'media', params: node.params });
        out.append(target);
      }
      node.each((inner) => {
        if (inner.type === 'comment') return;
        const k = '@media ' + node.params + '|' + inner.toString().replace(/\s+/g, ' ');
        if (seen.has(k)) return;
        seen.add(k);
        target.append(inner.clone());
      });
      return;
    }
    const k = key(node);
    if (seen.has(k)) return;
    seen.add(k);
    out.append(node.clone());
  });
}
scopeRules(out, scopeNew, (n) => 'v2-' + n);
const header = '/* GENERATED by scripts/build-v2-css.mjs from design-handoff/design (V18-V24). Do not edit by hand:\n   page-specific overrides go in src/app/v2-app.css. */\n';
fs.writeFileSync(OUT, header + out.toString() + '\n');
console.log('v2.css', fs.statSync(OUT).size, 'bytes from', files.length, 'pages');

// ---- old stylesheet: only on pages without a .v2 root -----------------------------------------------------------
if (process.argv.includes('--scope-old')) {
  const G = path.join(FRONT, 'src/app/globals.css');
  const txt = fs.readFileSync(G, 'utf8');
  if (txt.includes(':not(:has(.v2))')) {
    console.log('globals.css already scoped');
  } else {
    const root = postcss.parse(txt);
    const OLD = 'body:not(:has(.v2))';
    scopeRules(root, (sel) => {
      sel = sel.trim();
      if (sel === ':root' || sel.startsWith('@')) return sel;
      if (/^html\b/.test(sel)) return sel.replace(/^html/, 'html:not(:has(.v2))');
      if (/^body\b/.test(sel)) return sel.replace(/^body/, OLD);
      return `:where(${OLD}) ${sel}`;
    }, null);
    fs.writeFileSync(G, '/* Old (V11) styles: scoped by scripts/build-v2-css.mjs so they never touch redesigned (.v2) pages. */\n' + root.toString());
    console.log('globals.css scoped');
  }
}
